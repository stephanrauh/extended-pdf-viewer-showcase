// Generates src/assets/pdfs/cmyk-and-icc-demo.pdf: CMYK colors, a CMYK image and
// colors in an ICC-based color space, with an ICC profile this script writes
// itself. We created every byte of the file, so there are no copyright issues -
// this script is the proof.
//
//   node pdf-creator/make-cmyk-demo.mjs
//
// The e2e tests (T51) check the rendered colors at the positions below, so
// keep SWATCHES, IMAGE and ICC_SWATCHES in sync with them.
import { writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  PDFDocument,
  PDFName,
  PDFNumber,
  PDFOperator,
  StandardFonts,
  cmyk,
  concatTransformationMatrix,
  drawObject,
  popGraphicsState,
  pushGraphicsState,
} from 'pdf-lib';

// ---------------------------------------------------------------------------
// An ICC v2 display profile: sRGB primaries (adapted to D50, as ICC requires)
// and a simple gamma of 2.2. Written field by field after ICC.1:2001-04.
// ---------------------------------------------------------------------------
function iccProfile() {
  const s15Fixed16 = (v) => Math.round(v * 65536);
  const ascii = (s) => Buffer.from(s, 'ascii');
  const xyzTag = (x, y, z) => {
    const b = Buffer.alloc(20);
    b.write('XYZ ', 0, 'ascii');
    b.writeInt32BE(s15Fixed16(x), 8);
    b.writeInt32BE(s15Fixed16(y), 12);
    b.writeInt32BE(s15Fixed16(z), 16);
    return b;
  };
  const curveTag = (gamma) => {
    const b = Buffer.alloc(14);
    b.write('curv', 0, 'ascii');
    b.writeUInt32BE(1, 8); // one entry: a plain gamma value
    b.writeUInt16BE(Math.round(gamma * 256), 12); // u8Fixed8Number
    return b;
  };
  const descTag = (text) => {
    const t = Buffer.concat([ascii(text), Buffer.from([0])]);
    const b = Buffer.alloc(12 + t.length + 4 + 4 + 2 + 1 + 67);
    b.write('desc', 0, 'ascii');
    b.writeUInt32BE(t.length, 8);
    t.copy(b, 12);
    return b; // the Unicode and ScriptCode parts stay empty
  };
  const textTag = (text) => Buffer.concat([ascii('text'), Buffer.alloc(4), ascii(text), Buffer.from([0])]);

  const tags = [
    ['desc', descTag('extended-pdf-viewer-showcase demo RGB (gamma 2.2)')],
    ['cprt', textTag('No copyright, use freely. Generated by pdf-creator/make-cmyk-demo.mjs')],
    ['wtpt', xyzTag(0.9642, 1.0, 0.8249)],
    ['rXYZ', xyzTag(0.4361, 0.2225, 0.0139)],
    ['gXYZ', xyzTag(0.3851, 0.7169, 0.0971)],
    ['bXYZ', xyzTag(0.1431, 0.0606, 0.7141)],
    ['rTRC', curveTag(2.2)],
    ['gTRC', curveTag(2.2)],
    ['bTRC', curveTag(2.2)],
  ];
  const pad4 = (n) => (n + 3) & ~3;
  const tableSize = 4 + tags.length * 12;
  let offset = pad4(128 + tableSize);
  const table = Buffer.alloc(tableSize);
  table.writeUInt32BE(tags.length, 0);
  const data = [];
  tags.forEach(([signature, body], i) => {
    table.write(signature, 4 + i * 12, 'ascii');
    table.writeUInt32BE(offset, 8 + i * 12);
    table.writeUInt32BE(body.length, 12 + i * 12);
    const padded = Buffer.alloc(pad4(body.length));
    body.copy(padded);
    data.push(padded);
    offset += padded.length;
  });

  const header = Buffer.alloc(128);
  header.writeUInt32BE(offset, 0); // profile size
  header.writeUInt32BE(0x02100000, 8); // version 2.1
  header.write('mntr', 12, 'ascii'); // display device profile
  header.write('RGB ', 16, 'ascii');
  header.write('XYZ ', 20, 'ascii');
  [2026, 1, 1, 0, 0, 0].forEach((v, i) => header.writeUInt16BE(v, 24 + i * 2));
  header.write('acsp', 36, 'ascii');
  header.writeInt32BE(s15Fixed16(0.9642), 68); // PCS illuminant D50
  header.writeInt32BE(s15Fixed16(1.0), 72);
  header.writeInt32BE(s15Fixed16(0.8249), 76);

  const pre = Buffer.concat([header, table]);
  return Buffer.concat([pre, Buffer.alloc(pad4(pre.length) - pre.length), ...data]);
}

// ---------------------------------------------------------------------------
// The page. PDF coordinates: origin bottom left, 612 x 792 points.
// ---------------------------------------------------------------------------
export const SWATCHES = [
  { name: 'Cyan', color: [1, 0, 0, 0] },
  { name: 'Magenta', color: [0, 1, 0, 0] },
  { name: 'Yellow', color: [0, 0, 1, 0] },
  { name: 'Black', color: [0, 0, 0, 1] },
  { name: 'Red', color: [0, 1, 1, 0] },
  { name: 'Green', color: [1, 0, 1, 0] },
  { name: 'Blue', color: [1, 1, 0, 0] },
];
const SWATCH = { x: 50, y: 560, width: 60, height: 60, gap: 14 };
const IMAGE = { x: 50, y: 380, width: 504, height: 100, pixelsWide: 252, pixelsHigh: 50 };
const ICC_SWATCHES = [
  { name: 'Red', color: [0.9, 0.15, 0.1] },
  { name: 'Green', color: [0.1, 0.6, 0.2] },
  { name: 'Blue', color: [0.1, 0.3, 0.9] },
];
const ICC = { x: 50, y: 200, width: 100, height: 60, gap: 20 };

const doc = await PDFDocument.create();
doc.setTitle('CMYK colors and ICC color profiles');
doc.setAuthor('extended-pdf-viewer-showcase');
doc.setCreator('extended-pdf-viewer-showcase pdf-creator/make-cmyk-demo.mjs');
const page = doc.addPage([612, 792]);
const helvetica = await doc.embedFont(StandardFonts.Helvetica);
const bold = await doc.embedFont(StandardFonts.HelveticaBold);
const black = cmyk(0, 0, 0, 1);

page.drawText('CMYK colors and ICC color profiles', { x: 50, y: 730, size: 22, font: bold, color: black });
page.drawText('A test document for ngx-extended-pdf-viewer, generated by pdf-creator/make-cmyk-demo.mjs.', {
  x: 50, y: 705, size: 10, font: helvetica, color: black,
});

// 1. Areas in DeviceCMYK
page.drawText('Process colors (DeviceCMYK)', { x: 50, y: 640, size: 14, font: bold, color: black });
SWATCHES.forEach(({ name, color }, i) => {
  const x = SWATCH.x + i * (SWATCH.width + SWATCH.gap);
  page.drawRectangle({ x, y: SWATCH.y, width: SWATCH.width, height: SWATCH.height, color: cmyk(...color) });
  page.drawText(name, { x, y: SWATCH.y - 14, size: 9, font: helvetica, color: black });
});

// 2. An image in DeviceCMYK: cyan -> magenta -> yellow from left to right
page.drawText('An image in DeviceCMYK', { x: 50, y: 500, size: 14, font: bold, color: black });
const pixels = Buffer.alloc(IMAGE.pixelsWide * IMAGE.pixelsHigh * 4);
for (let row = 0; row < IMAGE.pixelsHigh; row++) {
  for (let col = 0; col < IMAGE.pixelsWide; col++) {
    const t = col / (IMAGE.pixelsWide - 1);
    const c = t < 0.5 ? 1 - 2 * t : 0;
    const m = t < 0.5 ? 2 * t : 2 - 2 * t;
    const y = t < 0.5 ? 0 : 2 * t - 1;
    const i = (row * IMAGE.pixelsWide + col) * 4;
    pixels[i] = Math.round(c * 255);
    pixels[i + 1] = Math.round(m * 255);
    pixels[i + 2] = Math.round(y * 255);
    pixels[i + 3] = 0;
  }
}
const imageRef = doc.context.register(
  doc.context.stream(deflateSync(pixels), {
    Type: 'XObject',
    Subtype: 'Image',
    Width: IMAGE.pixelsWide,
    Height: IMAGE.pixelsHigh,
    ColorSpace: 'DeviceCMYK',
    BitsPerComponent: 8,
    Filter: 'FlateDecode',
  }),
);
const imageName = page.node.newXObject('CmykImage', imageRef);
page.pushOperators(
  pushGraphicsState(),
  concatTransformationMatrix(IMAGE.width, 0, 0, IMAGE.height, IMAGE.x, IMAGE.y),
  drawObject(imageName),
  popGraphicsState(),
);

// 3. Areas in an ICC-based color space with our own profile
page.drawText('An ICC-based RGB color space (with our own ICC profile)', { x: 50, y: 320, size: 14, font: bold, color: black });
const profile = doc.context.register(doc.context.stream(iccProfile(), { N: 3, Alternate: 'DeviceRGB' }));
const colorSpace = doc.context.obj([PDFName.of('ICCBased'), profile]);
const resources = page.node.normalizedEntries().Resources;
const colorSpaces = doc.context.obj({ CS0: colorSpace });
resources.set(PDFName.of('ColorSpace'), colorSpaces);
ICC_SWATCHES.forEach(({ name, color }, i) => {
  const x = ICC.x + i * (ICC.width + ICC.gap);
  page.pushOperators(
    pushGraphicsState(),
    PDFOperator.of('cs', [PDFName.of('CS0')]),
    PDFOperator.of('scn', color.map((v) => PDFNumber.of(v))),
    PDFOperator.of('re', [x, ICC.y, ICC.width, ICC.height].map((v) => PDFNumber.of(v))),
    PDFOperator.of('f'),
    popGraphicsState(),
  );
  page.drawText(name, { x, y: ICC.y - 14, size: 9, font: helvetica, color: black });
});

const target = join(dirname(fileURLToPath(import.meta.url)), '../src/assets/pdfs/cmyk-and-icc-demo.pdf');
writeFileSync(target, await doc.save({ useObjectStreams: false }));
console.log(`wrote ${target}`);
